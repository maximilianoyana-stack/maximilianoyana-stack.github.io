function cambiarIdioma(idioma) {
    localStorage.setItem('idioma', idioma);
    actualizarTextos(idioma);
}

function obtenerIdioma() {
    return localStorage.getItem('idioma') || 'es';
}

function actualizarTextos(idioma) {
    const textos = idiomas[idioma];
    document.querySelectorAll('[data-i18n]').forEach(elemento => {
        const clave = elemento.getAttribute('data-i18n');
        if (textos[clave]) elemento.textContent = textos[clave];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(elemento => {
        const clave = elemento.getAttribute('data-i18n-placeholder');
        if (textos[clave]) elemento.placeholder = textos[clave];
    });

    if (idioma === 'ar' || idioma === 'he') document.documentElement.setAttribute('dir', 'rtl'); else document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.lang = idioma;
}

document.addEventListener('DOMContentLoaded', function() {
    const idioma = obtenerIdioma();
    actualizarTextos(idioma);
    actualizarSelectorIdioma(idioma);
});

function actualizarSelectorIdioma(idioma) {
    const selector = document.getElementById('idiomaSelector');
    if (selector) selector.value = idioma;
}
